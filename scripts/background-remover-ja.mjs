export function localizeJapanesePage(html) {
  const bodyStart = html.indexOf('<body>');
  if (bodyStart < 0) throw new Error('Background remover body not found');
  const head = html.slice(0, bodyStart);
  let body = html.slice(bodyStart).replace(/>([^<>]+)</g, (match, value) => {
    const trimmed = value.trim();
    if (!text.has(trimmed)) return match;
    return `>${value.slice(0, value.indexOf(trimmed))}${text.get(trimmed)}${value.slice(value.indexOf(trimmed) + trimmed.length)}<`;
  });
  body = body.replace(/(aria-label|title)="([^"]*)"/g, (match, name, value) =>
    attributes.has(value) ? `${name}="${attributes.get(value)}"` : match);
  return head + body;
}
